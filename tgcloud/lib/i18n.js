export function t(lang, key, params) {
  const strings = translations[lang] ?? translations[DEFAULT_LANGUAGE];
  let value = strings[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
  if (params) {
    value = value.replace(/\{(\w+)\}/g, (m, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m
    );
  }
  return value;
}
